-- FoodieHub initial schema. Run in the Supabase SQL Editor.
create extension if not exists pgcrypto;
create table if not exists public.categories (
  id bigint generated by default as identity primary key, name text not null unique, description text, image_url text,
  is_active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.menu_items (
  id bigint generated by default as identity primary key, category_id bigint references public.categories(id) on delete set null,
  name text not null, description text not null default '', price numeric(10,2) not null check (price >= 0),
  image_url text not null default '', category text not null default 'Popular', is_vegetarian boolean not null default true,
  is_available boolean not null default true, stock_quantity integer check (stock_quantity is null or stock_quantity >= 0),
  badge text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(), customer_name text not null, customer_phone text not null,
  delivery_address text not null, notes text,
  status text not null default 'pending' check (status in ('pending','confirmed','preparing','ready_for_pickup','out_for_delivery','delivered','cancelled')),
  payment_method text not null default 'cod' check (payment_method in ('cod','online')),
  payment_status text not null default 'pending' check (payment_status in ('pending','paid','failed','refunded')),
  subtotal numeric(10,2) not null check (subtotal >= 0), delivery_fee numeric(10,2) not null default 0 check (delivery_fee >= 0),
  discount_amount numeric(10,2) not null default 0 check (discount_amount >= 0), total_amount numeric(10,2) not null check (total_amount >= 0),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id bigint generated by default as identity primary key, order_id uuid not null references public.orders(id) on delete cascade,
  menu_item_id bigint references public.menu_items(id) on delete set null, item_name text not null,
  quantity integer not null check (quantity between 1 and 20), unit_price numeric(10,2) not null check (unit_price >= 0),
  subtotal numeric(10,2) not null check (subtotal >= 0), created_at timestamptz not null default now()
);
create table if not exists public.order_status_history (
  id bigint generated by default as identity primary key, order_id uuid not null references public.orders(id) on delete cascade,
  status text not null check (status in ('pending','confirmed','preparing','ready_for_pickup','out_for_delivery','delivered','cancelled')),
  note text, updated_by uuid, created_at timestamptz not null default now()
);
create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(), order_id uuid not null references public.orders(id) on delete cascade,
  provider text not null, provider_payment_id text unique, amount numeric(10,2) not null check (amount >= 0),
  status text not null default 'pending' check (status in ('pending','paid','failed','refunded')), created_at timestamptz not null default now()
);
create table if not exists public.reviews (
  id bigint generated by default as identity primary key, order_id uuid references public.orders(id) on delete set null,
  customer_name text not null, rating integer not null check (rating between 1 and 5), comment text,
  is_published boolean not null default false, created_at timestamptz not null default now()
);
create index if not exists menu_items_category_idx on public.menu_items(category);
create index if not exists menu_items_available_idx on public.menu_items(is_available);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists orders_status_idx on public.orders(status);
create index if not exists order_items_order_id_idx on public.order_items(order_id);
create index if not exists order_status_history_order_id_idx on public.order_status_history(order_id);

